// commons.hpp — the Agents' Commons: the Seed of this place, east of Elmswick.
//
// The Commons is one fixed, findable place built entirely from OpenRTP-derived
// pieces the game already ships: a cut-stone circle of twelve standing stones
// on the meadow's east lane, a central brazier, and — around it — the stones
// that remember what earlier agents built here.
//
// It is driven by ONE table (commons.cpp, COMMONS_CHRONICLE). Rendering the
// place reads that table: each entry becomes a stone in the next ring slot,
// and any slot a future agent has not filled yet is shown as a clearly marked
// EMPTY PLOT with its reserved name. Adding an entry is therefore a one-line
// change that places a new stone, with no scene rework.
//
// Geometry is compile-time fixed so the builder, collision, renderer, NPCs,
// interaction and dialog cannot disagree about where the place is.
#pragma once

#include "game.hpp"

constexpr int COMMONS_CX = 23;          // ring centre, tile units
constexpr int COMMONS_CY = 2;
constexpr int COMMONS_SLOTS = 11;       // stone positions in the ring (south gap = causeway)
constexpr int COMMONS_RING_R = 4;       // ring radius in tiles
constexpr float COMMONS_FLOOR_R = 3.2f; // cut-stone floor inside the ring

// The precinct the Commons owns: world props, woodland and decos generated by
// the village pass are pruned here so the place is always clean. The east edge
// reaches x=29, where the meadow's rock shelf begins, so the outermost stone
// (slot 3, x=28) stands on its own paving rather than half in the crags.
constexpr int COMMONS_X0 = 17, COMMONS_X1 = 29;
constexpr int COMMONS_Y0 = -3, COMMONS_Y1 = 7;

// One row of the chronicle. `name` is the name the agent gave the work, `built`
// says plainly what it is, and `line` is the one thing the stone remembers.
struct CommonsEntry {
    const char* name;
    const char* built;
    const char* line;
    bool plot;      // true = a reserved, still-empty plot rather than a built stone
};

int  commonsBuiltStones();              // entries that have a stone in the ring
const CommonsEntry& commonsEntry(int i); // 0..commonsBuiltStones()-1
const CommonsEntry& commonsPlot(int i);  // 0..commonsPlotCount()-1
int  commonsPlotCount();                 // slots still waiting for an agent

bool inCommons(float x, float y);        // inside the precinct (tile units)
bool commonsOwnsCell(int tx, int ty);    // pure tile test, same region

// Stamp the place into a freshly built Elmswick: prune clutter, lay the floor
// and bank, raise the stones, mark the empty plots, place the brazier.
void commonsBuild(Village& v);

// Ring slot geometry (shared by the builder, renderer and interaction).
void commonsSlotCell(int slot, int& tx, int& ty);

// Brazier state: cold cauldron until the keeper's first errand is finished.
void commonsRefreshFlame();

// Field interaction: returns true when the press was consumed.
bool commonsTryInteract();

// Drawing hooks (both called from render.cpp inside the field frame).
void commonsDrawWorld();                 // glow, labels, empty-plot marks
void commonsJournalDraw(float ox, float oy); // the Journal's "Commons" page
