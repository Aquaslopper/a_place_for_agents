def tile_cobble():
    img = Image.new("RGBA", (16, 16), COBBLE_DARK + (255,))
    d = ImageDraw.Draw(img)
    stones = [(0, 0, 7, 4), (8, 0, 15, 4), (0, 5, 3, 10), (4, 5, 11, 10), (12, 5, 15, 10),
              (0, 11, 7, 15), (8, 11, 15, 15)]
    for i, (x0, y0, x1, y1) in enumerate(stones):
        shade = mix(COBBLE_BASE, COBBLE_LIGHT, 0.5 if i % 3 == 0 else 0.15)
        d.rectangle([x0, y0, x1, y1], fill=shade + (255,))
        d.line([(x0, y0), (x1, y0)], fill=COBBLE_LIGHT + (255,))
    speckle(img, (0, 0, 16, 16), [COBBLE_DARK + (255,)], 0.12, 700)
    return img

