def house(variant):
    w, h = 66, 52
    img = new(w, h)
    d = ImageDraw.Draw(img)
    wall = [C("#d8cfb8"), C("#cbb894"), C("#b8c0cc")][variant]
    wall_d = mix(wall, (0, 0, 0), 0.35)
    roof = [C("#a8503a"), C("#3a5a8a"), C("#4d6b35")][variant]
    roof_d = mix(roof, (0, 0, 0), 0.4)
    roof_hi = mix(roof, (255, 255, 255), 0.25)
    # main body
    d.rectangle([6, 20, w - 7, h - 1], fill=wall + (255,))
    d.line([(6, 20), (6, h - 1)], fill=wall_d + (255,))
    d.line([(w - 7, 20), (w - 7, h - 1)], fill=wall_d + (255,))
    # timber framing
    for x in (14, w // 2, w - 16):
        d.line([(x, 21), (x, h - 1)], fill=wall_d + (255,))
    # roof (big trapezoid)
    d.polygon([(0, 22), (w // 2, 0), (w - 1, 22)], fill=roof + (255,))
    d.polygon([(0, 22), (w - 1, 22), (w - 6, 26), (6, 26)], fill=roof_d + (255,))
    d.line([(w // 2, 0), (4, 21)], fill=roof_hi + (255,), width=2)
    # roof tile ridges
    for y in (7, 12, 17):
        t = (y / 22)
        xl = int(w // 2 - (w // 2 + 4) * t); xr = int(w // 2 + (w // 2 + 4) * t)
        d.line([(xl, y), (xr, y)], fill=roof_d + (255,))
    # chimney
    d.rectangle([w - 15, 6, w - 10, 14], fill=C("#8a8a8a") + (255,))
    d.rectangle([w - 16, 4, w - 9, 7], fill=C("#6e6e6e") + (255,))
    # door
    d.rectangle([w // 2 - 4, h - 15, w // 2 + 4, h - 1], fill=C("#4d3520") + (255,))
    d.line([(w // 2 - 4, h - 15), (w // 2 + 4, h - 15)], fill=C("#6b4f31") + (255,))
    d.point((w // 2 + 2, h - 8), fill=C("#e8c86a") + (255,))
    # windows
    for x in (12, w - 19):
        d.rectangle([x, 32, x + 7, 39], fill=C("#2a3038") + (255,))
        d.rectangle([x + 1, 33, x + 6, 38], fill=C("#f0d878") + (255,))
        d.line([(x + 3, 33), (x + 3, 38)], fill=C("#2a3038") + (255,))
        d.line([(x + 1, 35), (x + 6, 35)], fill=C("#2a3038") + (255,))
    return img

