GRASS_BASE   = C("#3f8a4b")
GRASS_DARK   = C("#2f6e3c")
GRASS_LIGHT  = C("#58a45f")
GRASS_BRIGHT = C("#71b96c")
SAND_BASE    = C("#d9c079"); SAND_DARK  = C("#b3a05c"); SAND_LIGHT = C("#ecdcb0")
DIRT_BASE    = C("#8a6a45"); DIRT_DARK  = C("#6b4f31"); DIRT_LIGHT = C("#a8875c")
SNOW_BASE    = C("#e9e9f2"); SNOW_DARK  = C("#b9b9d4"); SNOW_LIGHT = C("#ffffff")
WATER_BASE   = C("#2b5f9e"); WATER_DEEP = C("#1d4070"); WATER_LIGHT= C("#4f83c4"); FOAM = C("#bcd8f2")
ROCK_BASE    = C("#7d7d84"); ROCK_DARK  = C("#57575f"); ROCK_LIGHT = C("#a3a3ab")
COBBLE_BASE  = C("#9b9b90"); COBBLE_DARK= C("#6e6e64"); COBBLE_LIGHT=C("#c2c2b4")

def tile_grass(variant):
    img = Image.new("RGBA", (16, 16), GRASS_BASE + (255,))
    d = ImageDraw.Draw(img)
    rnd = random.Random(100 + variant)
    # horizontal shade streaks
    for _ in range(10):
        y = rnd.randrange(16); x = rnd.randrange(16); w = rnd.randrange(2, 6)
        col = GRASS_DARK if rnd.random() < 0.6 else GRASS_LIGHT
        d.line([(x, y), (min(15, x + w), y)], fill=col + (255,))
    speckle(img, (0, 0, 16, 16), [GRASS_LIGHT + (255,), GRASS_BRIGHT + (255,), GRASS_DARK + (255,)], 0.16, 300 + variant)
    return img

def tile_tuft(variant):
    img = tile_grass(variant).copy()
    d = ImageDraw.Draw(img)
    rnd = random.Random(400 + variant)
    for _ in range(7):
        x = rnd.randrange(1, 14); y = rnd.randrange(4, 15)
        h = rnd.randrange(2, 4)
        d.line([(x, y), (x, y - h)], fill=GRASS_BRIGHT + (255,))
        d.line([(x - 1, y), (x - 1, y - h + 1)], fill=GRASS_LIGHT + (255,))
    return img

def tile_flower(variant):
    img = tile_grass(variant).copy()
    d = ImageDraw.Draw(img)
    rnd = random.Random(500 + variant)
    for _ in range(4):
        x = rnd.randrange(2, 14); y = rnd.randrange(2, 14)
        col = rnd.choice([C("#e86a6a"), C("#e8e06a"), C("#e88ad8"), C("#ffffff")])
        d.point((x, y), fill=col + (255,))
        d.point((x + 1, y), fill=col + (255,))
        d.point((x, y + 1), fill=col + (255,))
    return img

