def tile_water(frame):
    img = Image.new("RGBA", (16, 16), WATER_BASE + (255,))
    d = ImageDraw.Draw(img)
    # gradient to deep at bottom
    for y in range(16):
        img.paste(mix(WATER_BASE, WATER_DEEP, y / 22) + (255,), (0, y, 16, y + 1))
    offset = frame * 4
    for row, y in enumerate([3, 8, 13]):
        for x in range(-8, 24, 8):
            sx = (x + offset + row * 3) % 24 - 4
            d.line([(sx, y), (sx + 3, y)], fill=WATER_LIGHT + (255,))
    if frame == 1:
        d.point((5, 5), fill=FOAM + (255,)); d.point((12, 11), fill=FOAM + (255,))
    return img

