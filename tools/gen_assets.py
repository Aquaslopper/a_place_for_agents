SR = 22050

def _out_path(name):
    return os.path.join(ad("audio"), name)

def _save_ogg(samples, name):
    import numpy as np
    samples = np.clip(samples, -0.89, 0.89).astype(np.float32)
    try:
        import soundfile as sf
        path = _out_path(name + ".ogg")
        sf.write(path, samples, SR, format="OGG", subtype="VORBIS")
    except Exception as e:
        import wave
        path = _out_path(name + ".wav")
        pcm = (samples * 32767).astype(np.int16)
        with wave.open(path, "wb") as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
            w.writeframes(pcm.tobytes())
        print("soundfile unavailable (%s), wrote wav fallback" % e)
    print("wrote", os.path.relpath(path, ROOT))

def _midi_freq(m):
    return 440.0 * (2 ** ((m - 69) / 12))

def _env(n, attack=0.008, release=0.06):
    import numpy as np
    e = np.ones(n, dtype=np.float32)
    a = min(int(attack * SR), n)
    r = min(int(release * SR), n)
    if a > 0: e[:a] = np.linspace(0.0, 1.0, a)
    if r > 0: e[-r:] = np.linspace(1.0, 0.0, r)
    return e

def square(freq, n, vol=0.5, detune=0.0):
    import numpy as np
    t = np.arange(n) / SR
    s = np.sign(np.sin(2 * np.pi * freq * (1 + detune) * t) + 0.08 * np.sin(4 * np.pi * freq * t))
    return (s * vol * _env(n)).astype(np.float32)

def tri(freq, n, vol=0.6):
    import numpy as np
    t = np.arange(n) / SR
    s = 2 * np.abs(2 * (t * freq % 1.0)) - 1
    return (s * vol * _env(n)).astype(np.float32)

def noise(n, vol=0.4, decay=0.2):
    import numpy as np
    s = np.random.uniform(-1, 1, n).astype(np.float32)
    e = np.exp(-np.arange(n) / (decay * SR))
    return s * e * vol

def kick(n, vol=0.8):
    import numpy as np
    t = np.arange(n) / SR
    f = 110 * np.exp(-t * 18) + 38
    s = np.sin(2 * np.pi * np.cumsum(f) / SR)
    return (s * np.exp(-t * 9) * vol).astype(np.float32)

def render_song(notes, total_beats, bpm, name, swing=0.0):
    """notes: list of (midi or None, start_beat, beats, vel, voice)"""
    import numpy as np
    beat = 60.0 / bpm
    total = int(total_beats * beat * SR) + SR // 2
    mix = np.zeros(total, dtype=np.float32)
    for midi, start, beats, vel, voice in notes:
        n = int(beats * beat * SR)
        off = int(start * beat * SR)
        if midi is None:
            seg = noise(n, vol=0.25 * vel, decay=0.09)
        else:
            f = _midi_freq(midi)
            if voice == "lead":
                seg = square(f, n, vol=0.42 * vel, detune=0.004) + square(f, n, vol=0.22 * vel, detune=-0.005)
            elif voice == "bass":
                seg = tri(f, n, vol=0.55 * vel)
            elif voice == "pad":
                seg = square(f, n, vol=0.10 * vel, detune=0.006) + square(f, n, vol=0.10 * vel, detune=-0.006) + tri(f, n, vol=0.12 * vel)
            else:
                seg = square(f, n, vol=0.3 * vel)
        seg = seg[:mix.shape[0] - off]
        mix[off:off + len(seg)] += seg
    # head/tail gentle fade for loopability
    fade = int(0.25 * SR)
    mix[:fade] *= np.linspace(0, 1, fade)
    mix[-fade:] *= np.linspace(1, 0, fade)
    peak = np.max(np.abs(mix))
    if peak > 0.85: mix *= 0.85 / peak
    _save_ogg(mix, name)

